FROM BUCHUNG
WHERE (sqlc.arg(id_herden) = -1
   OR ID_HERDEN = sqlc.arg(id_herden))
  AND (sqlc.arg(only_active) = 0
   OR EXISTS (SELECT 1 FROM HERDEN H WHERE H.ID = BUCHUNG.ID_HERDEN
  AND H.AKTIV = 1))
ORDER BY year DESC;

